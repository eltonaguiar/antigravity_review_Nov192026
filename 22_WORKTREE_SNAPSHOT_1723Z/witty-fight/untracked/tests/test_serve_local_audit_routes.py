"""Route-resolution tests for the local /audit2 and /audit3 mirrors.

The live site serves these as directories; locally the files live in
audit_dashboard/ and audit_dashboard/data/. A wrong alias means the page 404s
its own ledger and silently renders "unavailable" — which is exactly what
happened before 2026-11-19.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tools.serve_local import (  # noqa: E402
    AUDIT_DIRECTORY_INDEX,
    AUDIT_DOCS_ROOT,
    AUDIT_LIVE_ALIASES,
)


def test_directory_urls_resolve_to_a_known_page():
    assert AUDIT_DIRECTORY_INDEX["/audit2"] == "/audit2/audit2.html"
    assert AUDIT_DIRECTORY_INDEX["/audit2/"] == "/audit2/audit2.html"
    assert AUDIT_DIRECTORY_INDEX["/audit3"] == "/audit3/index.html"
    assert AUDIT_DIRECTORY_INDEX["/audit3/"] == "/audit3/index.html"
    for key in AUDIT_DIRECTORY_INDEX.values():
        assert key in AUDIT_LIVE_ALIASES, key


def test_every_sidecar_the_pages_fetch_is_mapped():
    # audit2.js LEDGER_PATHS + forward fetch
    assert "/audit2/audit2.js" in AUDIT_LIVE_ALIASES
    assert "/audit2/audit2_forward.json" in AUDIT_LIVE_ALIASES
    assert "/audit2/audit3_ledger.json" in AUDIT_LIVE_ALIASES
    # audit3.html fetchJsonWithFallback targets
    assert "/audit3/audit3_ledger.json" in AUDIT_LIVE_ALIASES
    assert "/audit3/audit3_evidence.json" in AUDIT_LIVE_ALIASES


def test_mapped_files_exist_or_are_a_known_absent_artifact():
    """All mapped targets must exist, except the optional forward sidecar.

    audit2_forward.json is generated by tools/audit2_forward_summary.py; a fresh
    checkout may not have it yet, and the page handles that as "no rows" rather
    than a wiring failure. Everything else must be present, or the route is dead.
    """
    allowed_absent = {"audit2_forward.json"}
    missing = [target for target in AUDIT_LIVE_ALIASES.values()
               if not target.is_file() and target.name not in allowed_absent]
    assert not missing, missing


def test_all_targets_stay_inside_the_audit_dashboard_tree():
    root = AUDIT_DOCS_ROOT.resolve()
    for url, target in AUDIT_LIVE_ALIASES.items():
        resolved = target.resolve()
        assert resolved == root or root in resolved.parents, (url, resolved)
